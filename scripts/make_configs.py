"""公式の特権情報あり設定から、条件ごとの設定ファイルを configs/<cond>/<task>.yaml に作る。

条件:
  noisy      位置に誤差（1回で答える）
  nograsp    掴み方の補助なし（1回で答える）
  noisy_mt   位置に誤差 + 実行結果（標準出力・エラー）を見て直せる複数ターン
  base_mt    公式のまま + 複数ターン
  skill      公式のまま + スキルライブラリ（skill_lib/<task>.md をタスク文の後ろに足す。stack・nut・handover のみ）
  skill_mt   skill + 複数ターン

スキルの注入は設定ファイルの env.cfg.prompt で行う（CaP-X 本体は変えない）。
CaP-X はタスク文を cfg.prompt（無ければクラスの既定 PROMPT）から取り、
「タスク文 + "\nAPIs:\n" + API の説明」をプロンプトにする。skill ではタスク文を
「既定の PROMPT + "\n" + スキルの文面」にするので、見本の部分を除けば base と1文字も変わらない。
既定の PROMPT は CaP-X の venv（run_grid.py の CAPX_PYTHON）でクラスを import して読む。
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent

sys.path.insert(0, str(Path(__file__).resolve().parent))
from run_grid import CAPX, PY, TASKS  # noqa: E402

# CaP-X の公式の複数ターン用プロンプト（cube_lifting_multiturn.yaml と同じ文面）
MULTI_TURN_PROMPT = """The following code blocks were just executed:
```python
{executed_code}
```
The current console stdout is:
```
{console_stdout}
```
The current console stderr is:
```
{console_stderr}
```
If there were no errors during compilation or execution, the console stderr will be empty. If there were errors, consider regenerating the code.
Consider querying the environment state through tool calls and prints to see if the task is completed.
Please respond with EXACTLY ONE of the following:
- The word 'REGENERATE' followed immediately by new Python code in a fenced code block (```python...```) if you want to modify the code.
- The word 'FINISH' if the task appears to be complete
"""

CONDS = {
    "noisy": {"suffix": "_Noisy", "multi_turn": False},
    "nograsp": {"suffix": "_NoGrasp", "multi_turn": False},
    "noisy_mt": {"suffix": "_Noisy", "multi_turn": True},
    "base_mt": {"suffix": "", "multi_turn": True},
    "skill": {"suffix": "", "multi_turn": False, "skill": True},
    "skill_mt": {"suffix": "", "multi_turn": True, "skill": True},
}
SKILL_TASKS = ("stack", "nut", "handover")
SKILL_DIR = ROOT / "skill_lib"


def default_prompts(tasks: list[str]) -> dict[str, str]:
    """各タスクの環境クラスの既定のタスク文（クラス属性 prompt）を CaP-X の venv で読む。"""
    targets = {t: yaml.safe_load((CAPX / TASKS[t]).read_text())["env"]["_target_"] for t in tasks}
    code = (
        "import importlib, json, sys\n"
        "targets = json.loads(sys.argv[1])\n"
        "out = {}\n"
        "for task, target in targets.items():\n"
        "    mod, cls = target.rsplit('.', 1)\n"
        "    out[task] = getattr(importlib.import_module(mod), cls).prompt\n"
        "print('@@JSON@@' + json.dumps(out))\n"
    )
    res = subprocess.run([str(PY), "-c", code, json.dumps(targets)], cwd=CAPX, capture_output=True, text=True)
    marker = [ln for ln in res.stdout.splitlines() if ln.startswith("@@JSON@@")]
    if res.returncode != 0 or not marker:
        raise RuntimeError(f"could not read default prompts with {PY}:\n{res.stderr[-2000:]}")
    return json.loads(marker[-1][len("@@JSON@@"):])


def skill_prompt(default: str, skill_text: str) -> str:
    """既定のタスク文の後ろにスキルの文面を足す（CaP-X がこの後に "\nAPIs:\n..." を付ける）。"""
    return default + "\n" + skill_text


class _LiteralDumper(yaml.SafeDumper):
    """複数行の文字列を | 形式で書く（skill の設定を読みやすくするため。中身は同じ）。"""


def _str_presenter(dumper: yaml.SafeDumper, data: str) -> yaml.Node:
    if "\n" in data:
        return dumper.represent_scalar("tag:yaml.org,2002:str", data, style="|")
    return dumper.represent_scalar("tag:yaml.org,2002:str", data)


_LiteralDumper.add_representer(str, _str_presenter)


def main() -> None:
    defaults: dict[str, str] = {}
    if any(spec.get("skill") for spec in CONDS.values()):
        defaults = default_prompts(list(SKILL_TASKS))
    for cond, spec in CONDS.items():
        out_dir = ROOT / "configs" / cond
        out_dir.mkdir(parents=True, exist_ok=True)
        tasks = SKILL_TASKS if spec.get("skill") else tuple(TASKS)
        for task in tasks:
            rel = TASKS[task]
            cfg = yaml.safe_load((CAPX / rel).read_text())
            env_cfg = cfg["env"]["cfg"]
            env_cfg["apis"] = [a + spec["suffix"] for a in env_cfg["apis"]]
            dumper = yaml.SafeDumper
            if spec.get("skill"):
                assert "prompt" not in env_cfg, f"{rel} already overrides prompt"
                skill_text = (SKILL_DIR / f"{task}.md").read_text()
                env_cfg["prompt"] = skill_prompt(defaults[task], skill_text)
                dumper = _LiteralDumper
            if spec["multi_turn"]:
                env_cfg["multi_turn_prompt"] = MULTI_TURN_PROMPT
                cfg["use_legacy_multi_turn_decision_prompt"] = True
            # PyRoKi は外で起動しておくので自動起動の設定は残しても害はない（使用中なら飛ばされる）
            cfg["output_dir"] = f"./outputs/pai_{cond}_{task}"
            header = f"# generated by scripts/make_configs.py from {rel} (cond={cond})\n"
            if spec.get("skill"):
                header += f"# env.cfg.prompt = class default prompt + \"\\n\" + skill_lib/{task}.md\n"
            text = header + yaml.dump(cfg, Dumper=dumper, sort_keys=False, allow_unicode=True)
            if spec.get("skill"):  # 書いた YAML を読み戻して、文面が崩れていないことを確かめる
                back = yaml.safe_load(text)["env"]["cfg"]["prompt"]
                assert back == env_cfg["prompt"], f"YAML round-trip changed the prompt for {cond}/{task}"
            (out_dir / f"{task}.yaml").write_text(text)
        print(f"wrote configs/{cond}/ ({len(tasks)} tasks)")


if __name__ == "__main__":
    main()
